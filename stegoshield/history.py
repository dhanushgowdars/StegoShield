"""Private, local-only recent stego outputs for the Streamlit demonstration.

Only files generated by the application are saved. The history directory is
excluded from git. It is NOT encrypted, so it is not suitable for secrets.
"""
from __future__ import annotations

import json
import re
import uuid
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / ".stegoshield_data"
INDEX = ROOT / "index.json"
MAX_ITEMS = 8
MAX_ITEM_BYTES = 160 * 1024 * 1024
MAX_TOTAL_BYTES = 320 * 1024 * 1024


class HistoryError(RuntimeError):
    """Unable to read or save a recent generated file."""


def _read_index() -> list[dict]:
    if not INDEX.exists():
        return []
    try:
        data = json.loads(INDEX.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise HistoryError("Local history index could not be opened.") from exc
    if not isinstance(data, list):
        raise HistoryError("Local history index is invalid.")
    return [item for item in data if isinstance(item, dict)]


def _write_index(items: list[dict]) -> None:
    ROOT.mkdir(parents=True, exist_ok=True)
    temp = ROOT / ("index." + uuid.uuid4().hex + ".tmp")
    try:
        temp.write_text(json.dumps(items, ensure_ascii=False, indent=2), encoding="utf-8")
        temp.replace(INDEX)
    finally:
        temp.unlink(missing_ok=True)


def _entry_path(entry: dict) -> Path:
    # Do not trust arbitrary filenames in an on-disk index.
    file_id = entry.get("id", "")
    extension = entry.get("ext", "")
    if (not isinstance(file_id, str) or not re.fullmatch(r"[0-9a-f]{32}", file_id)
            or extension not in {"png", "wav", "mkv", "txt"}):
        raise HistoryError("History file reference is invalid.")
    return ROOT / f"{file_id}.{extension}"


def list_history() -> list[dict]:
    items = []
    for item in _read_index():
        try:
            path = _entry_path(item)
            if path.is_file():
                items.append(item)
        except HistoryError:
            continue
    return items


def load_history(entry_id: str) -> tuple[dict, bytes]:
    for entry in list_history():
        if entry["id"] == entry_id:
            try:
                return entry, _entry_path(entry).read_bytes()
            except OSError as exc:
                raise HistoryError("Could not read the saved stego file.") from exc
    raise HistoryError("Saved file not found. It may have been cleared.")


def save_history(data: bytes, *, display_name: str, fmt: str, mime: str) -> dict:
    if fmt not in {"Image", "Audio", "Video", "Text"}:
        raise HistoryError("Unsupported format for history.")
    ext = {"Image": "png", "Audio": "wav", "Video": "mkv", "Text": "txt"}[fmt]
    if len(data) > MAX_ITEM_BYTES:
        raise HistoryError("Generated file is too large for recent history. Please download it directly.")
    file_id = uuid.uuid4().hex
    item = {
        "id": file_id,
        "ext": ext,
        "name": Path(display_name).name,
        "format": fmt,
        "mime": mime,
        "size": len(data),
        "created": datetime.now().strftime("%d %b · %I:%M %p"),
    }
    ROOT.mkdir(parents=True, exist_ok=True)
    filepath = _entry_path(item)
    try:
        filepath.write_bytes(data)
        prior = list_history()
        retained = [item]
        total_size = len(data)
        for older in prior:
            size = int(older.get("size", 0))
            if len(retained) < MAX_ITEMS and total_size + size <= MAX_TOTAL_BYTES:
                retained.append(older)
                total_size += size
        _write_index(retained)
        retained_ids = {obj["id"] for obj in retained}
        for older in prior:
            if older["id"] not in retained_ids:
                _entry_path(older).unlink(missing_ok=True)
    except (OSError, HistoryError) as exc:
        # Encoding succeeded even if the optional local history cache cannot save it.
        filepath.unlink(missing_ok=True)
        raise HistoryError("Could not save a local recent-file copy.") from exc
    return item


def clear_history() -> None:
    for item in list_history():
        try:
            _entry_path(item).unlink(missing_ok=True)
        except OSError as exc:
            raise HistoryError("Could not delete a saved recent file.") from exc
    _write_index([])
